# shellcheck shell=bash
# The headless backend (DEVKIT_BACKEND=headless, the default for an app: DEVKIT_APP_CMD), sourced by lib/session.sh.
#
# The session is a sway with no window, monitor, focus or seat on your desktop: WLR_BACKENDS=headless gives it one virtual output
# (HEADLESS-1) and no input device, it lives in a private 0700 XDG_RUNTIME_DIR of its own (so its Wayland and sway sockets are
# nowhere your compositor or your apps look), and every environment variable that names your compositor is removed from it. Nothing
# it does can be an event of your Hyprland: no window opens, no monitor appears, nothing takes or gives focus, nothing warps the pointer
# (why that matters: docs/how-it-works.md). Input is sent over its own socket, as with the other backend (vptr, wtype), and screenshots
# are grim's (wlr-screencopy), all of them given the private socket by absolute path and the private runtime dir.
#
# Variables it sets: NSWAY (sway's IPC socket), NWD (its Wayland socket, an absolute path), NSIG (an id, "headless-PID"; never given to
# hyprctl), NMON (HEADLESS-1). The caller (lib/session.sh) has set NEST, NEST_HOME, NEST_BIN, W, H.

# What names your compositor, your display or your seat: all of it is removed from the session's environment, and the session is not
# started if any is still there (headless_assert_clean).
HEADLESS_UNSET=(WAYLAND_DISPLAY WAYLAND_SOCKET DISPLAY HYPRLAND_INSTANCE_SIGNATURE HYPRLAND_CMD SWAYSOCK I3SOCK NIRI_SOCKET
  DBUS_SESSION_BUS_ADDRESS WLR_DRM_DEVICES WLR_RENDER_DRM_DEVICE)

headless_rt() { echo "$NEST/rt"; }

headless_requires() {
  local tool
  for tool in sway swaymsg dbus-run-session wtype grim jq gcc wayland-scanner pkg-config; do
    command -v "$tool" >/dev/null || { echo "devkit: the headless session needs $tool" >&2; return 1; }
  done
  # The private runtime dir holds sway's IPC socket; a socket path is limited to 107 bytes.
  ((${#NEST} + 40 < 107)) || { echo "devkit: the session's folder path is too long for sway's socket ($NEST); set TMPDIR or XDG_RUNTIME_DIR shorter" >&2; return 1; }
  app_command_path >/dev/null || { echo "devkit: DEVKIT_APP_CMD: cannot find an executable '${DEVKIT_APP_CMD[0]}' (build the app, or fix devkit.conf)" >&2; return 1; }
}

# sway's configuration for the session. One virtual output at the size asked for, no bar, no borders, no gaps, no Xwayland (no DISPLAY), a
# plain background: the one window of the app fills the screen, and a dialog it opens floats over it as on any desktop.
headless_conf_write() {
  local f=$NEST/sway.conf
  {
    printf '# Generated by omarchy-plugin-devkit (lib/headless.sh). The session'"'"'s only compositor config.\n'
    printf 'xwayland disable\n'
    printf 'default_border none\ndefault_floating_border none\nhide_edge_borders both\n'
    printf 'gaps inner 0\ngaps outer 0\n'
    printf 'focus_follows_mouse yes\n'
    printf 'output HEADLESS-1 mode %sx%s\n' "$W" "$H"
    printf 'output HEADLESS-1 scale 1\n'
    printf 'output * bg %s solid_color\n' "${DEVKIT_BG:-#262a36}"
  } >"$f"
}

# The environment sway starts with, as `env` arguments in HEADLESS_ENV: your compositor's variables out, the headless wlroots backend in.
headless_env_build() {
  local v rt; rt=$(headless_rt)
  HEADLESS_ENV=(env)
  for v in "${HEADLESS_UNSET[@]}"; do HEADLESS_ENV+=(-u "$v"); done
  HEADLESS_ENV+=(XDG_RUNTIME_DIR="$rt" WLR_BACKENDS=headless WLR_LIBINPUT_NO_DEVICES=1 WLR_RENDERER=pixman)
}
# Refuses unless the environment the session would get is clean: none of your compositor's variables, WLR_BACKENDS=headless, a private runtime dir.
headless_assert_clean() {
  local out v rt; rt=$(headless_rt)
  headless_env_build
  out=$("${HEADLESS_ENV[@]}" env) || { echo "devkit: could not build the headless session's environment" >&2; return 1; }
  for v in "${HEADLESS_UNSET[@]}"; do
    ! grep -q "^$v=" <<<"$out" || { echo "devkit: refusing to start: $v is set in the headless session's environment (it could reach your desktop)" >&2; return 1; }
  done
  grep -qx 'WLR_BACKENDS=headless' <<<"$out" || { echo "devkit: refusing to start: WLR_BACKENDS is not headless" >&2; return 1; }
  grep -qx "XDG_RUNTIME_DIR=$rt" <<<"$out" || { echo "devkit: refusing to start: XDG_RUNTIME_DIR is not the session's private one" >&2; return 1; }
  [[ -d $rt && $(stat -c %a "$rt") == 700 ]] || { echo "devkit: refusing to start: $rt is not a 0700 folder" >&2; return 1; }
}

# Mesa's EGL vendor file, which a GL client of the session is pointed at (with LIBGL_ALWAYS_SOFTWARE=1) so it never loads a GPU's.
headless_mesa_egl() {
  local f=/usr/share/glvnd/egl_vendor.d/50_mesa.json
  [[ -f $f ]] || f=$(find /usr/share/glvnd/egl_vendor.d -name '*mesa*.json' 2>/dev/null | head -n1)
  echo "${f:-/usr/share/glvnd/egl_vendor.d/50_mesa.json}"
}

# swaymsg to the session's sway, by socket path: never the default (an unset SWAYSOCK would find nothing, a set one could be yours).
headless_msg() { swaymsg -s "$NSWAY" "$@"; }
# A command run as a client of the session: its Wayland socket by absolute path and its runtime dir, none of your compositor's variables.
headless_client() {
  [[ -n ${NWD:-} && $NWD == "$(headless_rt)"/* ]] || { echo "devkit: refusing: the session's socket '${NWD:-}' is not inside its private runtime dir" >&2; return 1; }
  env -u HYPRLAND_INSTANCE_SIGNATURE -u HYPRLAND_CMD -u DISPLAY -u SWAYSOCK XDG_RUNTIME_DIR="$(headless_rt)" WAYLAND_DISPLAY="$NWD" SWAYSOCK="$NSWAY" "$@"
}
headless_alive() { [[ -n ${NSWAY:-} && -S $NSWAY ]] && headless_msg -t get_version >/dev/null 2>&1; }

headless_start() {
  local rt i pid sock s
  rt=$(headless_rt)
  mkdir -p "$NEST"
  rm -rf "$rt"; mkdir -m 700 "$rt"
  ledger_add dir "$rt"
  headless_conf_write
  nested_dbus_conf_write
  headless_assert_clean || return 1
  : >"$NEST/sway.log"
  setsid -f "${HEADLESS_ENV[@]}" dbus-run-session --config-file="$NEST/dbus.conf" -- sway -c "$NEST/sway.conf" >"$NEST/sway.log" 2>&1 </dev/null
  nest_pid=detached
  for i in $(seq 1 60); do
    s=$(find "$rt" -maxdepth 1 -name 'sway-ipc.*.sock' -print -quit 2>/dev/null)
    sock=$(find "$rt" -maxdepth 1 -name 'wayland-[0-9]*' ! -name '*.lock' -print -quit 2>/dev/null)
    [[ -n $s && -n $sock ]] && break
    sleep 0.25
  done
  if [[ -z $s || -z $sock ]]; then echo "devkit: the headless sway did not start (see $NEST/sway.log)" >&2; return 1; fi
  pid=${s##*/}; pid=${pid%.sock}; pid=${pid##*.}
  [[ $pid =~ ^[0-9]+$ ]] && ledger_add sway "$pid"
  NSWAY=$s
  NWD=$sock
  NSIG=headless-$pid
  NMON=HEADLESS-1
  for i in $(seq 1 40); do headless_alive && break; sleep 0.25; done
  headless_alive || { echo "devkit: the headless sway does not answer on $NSWAY (see $NEST/sway.log)" >&2; return 1; }
  headless_verify_size || return 1
  # The app starts once the screen has its size, so it never sees another one. It is a child of sway, as a program started from its config.
  if [[ ${DEVKIT_APP_MODE:-0} == 1 ]]; then
    [[ $NEST_BIN != *\'* ]] || { echo "devkit: the session's folder has a quote in its name" >&2; return 1; }
    headless_msg exec "'$NEST_BIN/app-launch'" >/dev/null || { echo "devkit: sway would not start the app" >&2; return 1; }
  fi
}

# The output must be HEADLESS-1 at exactly WxH: a session of another size makes every pixel a click names wrong.
headless_verify_size() {
  local i have
  for i in $(seq 1 20); do
    have=$(headless_msg -t get_outputs -r 2>/dev/null | jq -r '.[] | select(.name == "HEADLESS-1" and .active) | "\(.current_mode.width) \(.current_mode.height)"' 2>/dev/null)
    if [[ $have == "$W $H" ]]; then NW=$W; NH=$H; return 0; fi
    sleep 0.25
  done
  echo "devkit: the headless output is ${have:-missing}, wanted ${W}x${H}; not started (see $NEST/sway.log)" >&2
  return 1
}

# Is a window of the app mapped? Same meaning as the hyprland backend's: DEVKIT_APP_CLASS and DEVKIT_APP_TITLE are regular expressions on the
# window's app id (or X11 class) and its title; both empty means any window.
headless_window_up() {
  headless_msg -t get_tree -r 2>/dev/null | jq -e --arg c "${DEVKIT_APP_CLASS:-}" --arg t "${DEVKIT_APP_TITLE:-}" \
    '[recurse(.nodes[]?, .floating_nodes[]?) | select((.pid // 0) > 0)
      | select(((.app_id // "") | test($c)) or ((.window_properties.class // "") | test($c)))
      | select((.name // "") | test($t))] | length > 0' >/dev/null 2>&1
}
headless_windows() {
  headless_msg -t get_tree -r | jq -r '[recurse(.nodes[]?, .floating_nodes[]?) | select((.pid // 0) > 0)][] | "\(.app_id // .window_properties.class // "")\t\(.name // "")"'
}

headless_stop() {
  local rt i p
  rt=$(headless_rt)
  # What runs inside goes first, then the compositor.
  nested_procs _nested_term || true
  sleep 1
  if headless_alive; then headless_msg exit >/dev/null 2>&1 || true; fi
  for i in $(seq 1 20); do headless_alive || break; sleep 0.25; done
  nested_procs _nested_kill || true
  # A sway that was killed rather than quit leaves its sockets in the private folder, which is deleted whole.
  nest_pid=""
  [[ -n $rt && $rt == "$NEST"/rt ]] && rm -rf "${rt:?}"
  for p in $(procs_with "XDG_RUNTIME_DIR=$rt"); do kill -KILL "$p" 2>/dev/null || true; done
}
